"""批次5：界面与残留内容清理。

- 标题画面改用自制背景、中文按钮，关闭 MOG 示例标题精灵/示例背景
- 隐藏（不启用）旧任务 HUD，清空 26 条「任务xxx」占位任务
- 移除所有示例任务头顶标志，避免玩家看到无来源的问号
- 修正两处面向玩家的「接取了任务」提示
- 小地图颜色由示例配色改为低饱和配色（当前仍由开场地块关闭）
- 清理两张地图的临时命名
"""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
PROJ = ROOT / "工程"
DATA = PROJ / "data"


def load_json(path: Path):
    with path.open(encoding="utf-8") as f:
        return json.load(f)


def save_json(path: Path, obj) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        json.dump(obj, f, ensure_ascii=False, separators=(",", ":"))
        f.write("\n")


def load_plugins():
    text = (PROJ / "js" / "plugins.js").read_text(encoding="utf-8")
    start = text.index("[")
    end = text.rindex("]")
    return json.loads(text[start:end + 1])


def save_plugins(plugins) -> None:
    lines = ["// Generated by RPG Maker.",
             "// Do not edit this file directly.",
             "var $plugins =", "["]
    body = [json.dumps(p, ensure_ascii=False, separators=(",", ":")) for p in plugins]
    lines.append(",\n".join(body))
    lines.append("];")
    (PROJ / "js" / "plugins.js").write_text("\n".join(lines) + "\n", encoding="utf-8")


def remove_preceding_text_header(cmd_list, index):
    if index > 0 and cmd_list[index - 1]["code"] == 101:
        return index - 1
    return index


def cleanup_maps() -> int:
    removed_signs = 0
    for path in sorted(DATA.glob("Map*.json")):
        m = load_json(path)
        if not isinstance(m, dict) or "events" not in m:
            continue
        changed = False
        for ev in m.get("events", []):
            if not ev:
                continue
            for p in ev.get("pages", []) or []:
                lst = p.get("list", [])
                out = []
                i = 0
                while i < len(lst):
                    c = lst[i]
                    if (c["code"] == 357 and c["parameters"][0] == "XdRs_TaskSystem"
                            and c["parameters"][1] == "ChangeTaskSign"):
                        removed_signs += 1
                        changed = True
                        i += 1
                        # 跳过插件指令附带的 657 注释行
                        while i < len(lst) and lst[i]["code"] == 657:
                            i += 1
                        continue
                    out.append(c)
                    i += 1
                p["list"] = out
        if changed:
            save_json(path, m)
    return removed_signs


def fix_prologue_task_ui() -> None:
    path = DATA / "Map005.json"
    m = load_json(path)
    for ev in m["events"]:
        if not ev:
            continue
        if ev["id"] == 17:
            for p in ev["pages"]:
                p["list"] = [c for c in p["list"]
                             if not (c["code"] == 121 and len(c["parameters"]) >= 3
                                     and c["parameters"][0] == 12)]
            save_json(path, m)
        if ev["id"] == 18:
            for p in ev["pages"]:
                for c in p["list"]:
                    if c["code"] == 401 and "接取了主线任务" in c["parameters"][0]:
                        c["parameters"][0] = "（你把锁收进了口袋。）"
            save_json(path, m)

    path = DATA / "Map002.json"
    m = load_json(path)
    for ev in m["events"]:
        if ev and ev["id"] == 9:
            for p in ev["pages"]:
                for c in p["list"]:
                    if c["code"] == 401 and "接取了关于小娟的发卡任务" in c["parameters"][0]:
                        c["parameters"][0] = "（小娟用两根手指，比了比发卡的大小。）"
            save_json(path, m)


def cleanup_tasks() -> None:
    path = DATA / "Tasks.json"
    tasks = load_json(path)
    for i in range(5, len(tasks)):
        tasks[i] = None
    save_json(path, tasks)


def cleanup_system_and_maps() -> None:
    path = DATA / "System.json"
    system = load_json(path)
    system["title1Name"] = "Title_Main"
    save_json(path, system)

    path = DATA / "MapInfos.json"
    infos = load_json(path)
    for i, info in enumerate(infos):
        if not info:
            continue
        if i == 4 and info.get("name") == "游戏开场":
            info["name"] = "序章"
        if i == 42:
            info["name"] = "记忆深处"
    save_json(path, infos)


def cleanup_plugins(plugins) -> None:
    for p in plugins:
        if p["name"] == "MOG_TitlePictureCom":
            params = p["parameters"]
            params["Animation Mode"] = "0"
            params["Title Sprite"] = "false"
            params["Smart Background"] = "false"
            params["Cursor Wave Animation"] = "false"
            params["Cursor Rotation Animation"] = "false"
            params["Cursor X-Axis"] = "0"
            params["Cursor Y-Axis"] = "5"
            params["Command Pos 1"] = "650,470"
            params["Command Pos 2"] = "650,506"
            params["Command Pos 3"] = "650,542"
        if p["name"] == "KoTC Minimap Basic":
            params = p["parameters"]
            params["Minimap Scale"] = "120"
            params["Minimap Wall Color"] = "#6b6b6b"
            params["Player Map Indicator Color"] = "#f0e6d2"
            params["Minimap Background Color"] = "rgba(14,14,14,0.65)"
            params["Minimap Border Thickness"] = "1"
            params["Minimap Border Color"] = "rgba(240,230,210,0.35)"


def main() -> None:
    plugins = load_plugins()
    cleanup_plugins(plugins)
    save_plugins(plugins)

    cleanup_system_and_maps()
    cleanup_tasks()
    signs = cleanup_maps()
    fix_prologue_task_ui()
    print("removed task signs:", signs)


if __name__ == "__main__":
    main()
