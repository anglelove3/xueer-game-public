def fix_quotes(t):
    out, skipped = [], 0
    for ln in t.split("\n"):
        if ln.count('"') % 2 == 1:
            out.append(ln)
            skipped += 1
            continue
        res, op = [], True
        for ch in ln:
            if ch == '"':
                res.append("「" if op else "」")
                op = not op
            else:
                res.append(ch)
        out.append("".join(res))
    return "\n".join(out), skipped


def insert_status(t):
    lines = t.split("\n")
    for i, ln in enumerate(lines):
        if ln.startswith("# "):
            return "\n".join(lines[:i + 1] + STATUS_HEAD + lines[i + 1:]), True
    return t, False


