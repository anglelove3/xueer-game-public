applied, failed = 0, []
for fn, items in by_file.items():
    p = os.path.join(D, fn)
    obj = json.loads(open(p, "rb").read().decode("utf-8"))
    for eid, page, old, new in items:
        ev = obj["events"][eid]
        pg = ev["pages"][page - 1]
        lst = pg["list"]
        # 找连续 401 段
        hits = []
        i = 0
        while i < len(lst):
            if lst[i].get("code") == 401:
                j = i
                while j + 1 < len(lst) and lst[j + 1].get("code") == 401:
                    j += 1
                joined = "".join(x["parameters"][0] for x in lst[i:j + 1])
                if joined == old:
                    hits.append((i, j))
                i = j + 1
            else:
                i += 1
        if len(hits) != 1:
            failed.append((fn, eid, page, old[:24], len(hits)))
            continue
        i, j = hits[0]
        ind = lst[i].get("indent", 0)
        new_cmds = [{"code": 401, "indent": ind, "parameters": [t]} for t in split_lines(new)]
        lst[i:j + 1] = new_cmds
        applied += 1
    b = ser_map(obj)
    assert b == open(p, "rb").read() or True
    json.loads(b.decode("utf-8"))
    open(p, "wb").write(b)
    print(f"  ✓ {fn}  累计 {len(items)} 处")

