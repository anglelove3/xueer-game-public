c = lambda x: json.dumps(x, ensure_ascii=False, separators=(",", ":"))


def ser_map(o):
    ks = list(o.keys())
    head = ",".join(f'"{k}":{c(o[k])}' for k in ks if k not in ("data", "events"))
    return ("{\n" + head + ',\n"data":' + c(o["data"]) + ',\n"events":[\n'
            + ",\n".join(c(e) for e in o["events"]) + "\n]\n}").encode("utf-8")


# ---------------------------------------------------------------- 折行
CTRL = re.compile(r"\\[A-Za-z]+\[[^\]]*\]|\\[A-Za-z]+")


def split_lines(t, width=20):
    """按 ~20 字折行；标点优先断行；\\C[] / \\V[] 控制码视为原子；合并过短尾行"""
    atoms = re.findall(r"\\[A-Za-z]+\[[^\]]*\]|\\[A-Za-z]+|.", t)
    out, cur = [], ""
    for a in atoms:
        cur += a
        plain = CTRL.sub("", cur)
        if cur[-1] in "，。！？…、；：" and len(plain) >= width - 6:
            out.append(cur); cur = ""
        elif len(plain) >= width + 2:
            out.append(cur); cur = ""
    if cur:
        out.append(cur)
    merged = []
    for line in out:
        if merged and len(CTRL.sub("", line)) < 8 and \
           len(CTRL.sub("", merged[-1])) + len(CTRL.sub("", line)) <= 26:
            merged[-1] += line          # 避免「！」「出来的。」这类碎行单独占一行
        else:
            merged.append(line)
    return merged


